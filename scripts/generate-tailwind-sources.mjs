import assert from 'node:assert/strict';
import {readFile, readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const packages = [];

for (const directory of await readdir(path.join(root, 'packages'))) {
  const base = path.join(root, 'packages', directory);
  let pkg;
  try {
    pkg = JSON.parse(await readFile(path.join(base, 'package.json'), 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') continue;
    throw error;
  }
  if (pkg.private || !pkg.files?.includes('dist')) continue;
  const sources = await readdir(path.join(base, 'src'), {recursive: true});
  packages.push({
    base,
    pkg,
    hasComponents: sources.some((p) => p.endsWith('.tsx')),
  });
}

// Include packages that compose UI packages even if they have no JSX themselves.
const styled = new Set(
  packages.filter((p) => p.hasComponents).map((p) => p.pkg.name),
);
let previousSize;
do {
  previousSize = styled.size;
  for (const {pkg} of packages) {
    if (Object.keys(pkg.dependencies ?? {}).some((name) => styled.has(name))) {
      styled.add(pkg.name);
    }
  }
} while (previousSize !== styled.size);

for (const {base, pkg} of packages) {
  if (!styled.has(pkg.name)) continue;
  const imports = Object.keys(pkg.dependencies ?? {})
    .filter((name) => styled.has(name))
    .sort()
    .map((name) => `@import '${name}/tailwind.css';`);
  const css = [
    '/* Generated by scripts/generate-tailwind-sources.mjs. */',
    ...imports,
    '',
    '/* Compiled packages and live workspace sources, relative to this file. */',
    '@source "./dist/**/*.{js,mjs,cjs}";',
    '@source "./src/**/*.{ts,tsx}";',
    '',
  ].join('\n');
  if (check) {
    assert.equal(
      await readFile(path.join(base, 'tailwind.css'), 'utf8'),
      css,
      pkg.name,
    );
    assert(
      pkg.files.includes('tailwind.css'),
      `${pkg.name}: publish tailwind.css`,
    );
    assert(
      pkg.sideEffects === undefined ||
        pkg.sideEffects === true ||
        (Array.isArray(pkg.sideEffects) &&
          pkg.sideEffects.includes('**/*.css')),
      `${pkg.name}: preserve stylesheet side effects`,
    );
    if (pkg.exports) {
      assert.equal(pkg.exports['./tailwind.css'], './tailwind.css', pkg.name);
    }
  } else {
    await writeFile(path.join(base, 'tailwind.css'), css);
    if (!pkg.files.includes('tailwind.css')) pkg.files.push('tailwind.css');
    if (pkg.exports) pkg.exports['./tailwind.css'] = './tailwind.css';
    if (pkg.sideEffects === false) pkg.sideEffects = ['**/*.css'];
    else if (
      Array.isArray(pkg.sideEffects) &&
      !pkg.sideEffects.includes('**/*.css')
    ) {
      pkg.sideEffects.push('**/*.css');
    }
    await writeFile(
      path.join(base, 'package.json'),
      `${JSON.stringify(pkg, null, 2)}\n`,
    );
  }
}

console.log(
  `${check ? 'Checked' : 'Generated'} ${styled.size} Tailwind source entries.`,
);
